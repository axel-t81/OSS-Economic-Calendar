"""Catalogue of tracked indicators, loaded by `manage.py seed_indicators`.

Names are source-faithful (the publishing organisation's own terminology), not
calendar-isms. `standard_name` holds the generic, country-agnostic concept so
indicators can be compared across countries once non-AU calendars exist.

Fields: name, standard_name, frequency, measure, unit, source, source_release,
notes (optional). `is_active` is deliberately absent — reseeding must never
reactivate an indicator the maintainer has retired.
"""

